import { expect, test } from "@playwright/test";

test("provision, control, persist and inspect a real browser through Lit", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/");
  await page.getByRole("button", { name: "Create a new browser" }).click();
  const panel = page.locator("app-browser-panel").first();
  const address = panel.getByRole("textbox");
  await expect(address).toBeEnabled();
  await expect(panel.getByRole("tab")).toHaveCount(1);
  await address.fill("data:text/html," + encodeURIComponent("<title>Loading</title><textarea autofocus style='width:400px;height:200px'></textarea><script>onload=()=>document.title='Canon Stack'</script>"));
  await address.press("Enter");
  await expect(panel.getByRole("tab", { selected: true })).toContainText("Canon Stack");
  const canvas = panel.locator("canvas");
  await expect.poll(() => canvas.evaluate((element: HTMLCanvasElement) => element.getContext("2d")!.getImageData(0, 0, 1, 1).data[3])).toBe(255);
  await canvas.click({ position: { x: 20, y: 20 } });
  await page.keyboard.type("Canon clipboard");
  await page.keyboard.press("Control+a");
  await page.keyboard.press("Control+c");
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe("Canon clipboard");
  await page.evaluate(() => navigator.clipboard.writeText("Lit paste"));
  await page.keyboard.press("Control+v");
  await page.keyboard.press("Control+a");
  await page.keyboard.press("Control+c");
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe("Lit paste");
  await panel.getByRole("button", { name: "Open new tab" }).click();
  await expect(panel.getByRole("tab")).toHaveCount(2);
  await expect(panel.getByRole("tab", { selected: true })).not.toContainText("Canon Stack");
  await panel.getByRole("tab", { selected: true }).getByRole("button").click();
  await expect(panel.getByRole("tab")).toHaveCount(1);
  await panel.getByRole("button", { name: "Checkpoints & profiles" }).click();
  const checkpoint = panel.locator("app-browser-saved-state-card").filter({ hasText: "Browser Checkpoint" });
  await checkpoint.getByRole("button", { name: "Save", exact: true }).click();
  await expect(checkpoint.getByRole("button", { name: "Mount", exact: true })).toBeEnabled();
  await panel.getByRole("button", { name: "Close browser state menu" }).click();
  await page.getByRole("button", { name: "Focus", exact: true }).click();
  await expect(page).toHaveURL(/view=focus/);
  await page.getByRole("button", { name: "Admin", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Browser infrastructure" })).toBeVisible();
  await expect(page.locator("app-admin-session-card")).toHaveCount(1);
  await expect(page.locator("app-admin-browser-card")).toHaveCount(1);
  expect(errors).toEqual([]);
});
